-- 07_agent_tables.sql
-- The agent's own notebook: one row per goal (agent_runs) and one row per planned step (agent_actions).

create table agent_runs (
  id int generated by default as identity primary key,
  goal text not null,
  status text not null default 'planned'
    check (status in ('planned','in_progress','awaiting_approval','completed','failed','cancelled')),
  summary text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table agent_actions (
  id int generated by default as identity primary key,
  run_id int not null references agent_runs(id) on delete cascade,
  step_number int not null,
  description text not null,
  tool_name text,
  status text not null default 'planned'
    check (status in ('planned','awaiting_approval','completed','failed','denied','skipped')),
  result_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (run_id, step_number)
);

alter table agent_runs enable row level security;
alter table agent_actions enable row level security;

grant all on agent_runs to service_role;
grant all on agent_actions to service_role;
grant all on all sequences in schema public to service_role;

-- Only one open run per goal text
create unique index one_open_run_per_goal
on agent_runs (lower(goal))
where status in ('planned','in_progress','awaiting_approval');

-- Keep updated_at current on both tables
create function touch_updated_at() returns trigger as $$
begin
  new.updated_at := now();
  return new;
end;
$$ language plpgsql;

create trigger runs_touch before update on agent_runs
for each row execute function touch_updated_at();

create trigger actions_touch before update on agent_actions
for each row execute function touch_updated_at();

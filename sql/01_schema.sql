-- 01_schema.sql
-- Core FakeBusiness tables. Run first.

create table departments (
  id int generated by default as identity primary key,
  name text not null unique,
  description text
);

create table employees (
  id int generated by default as identity primary key,
  full_name text not null,
  email text not null unique,
  role_title text not null,
  department_id int not null references departments(id),
  manager_id int references employees(id),
  hire_date date not null,
  status text not null default 'active' check (status in ('active','on_leave','left')),
  weekly_capacity_hours int not null default 40
);

create table customers (
  id int generated by default as identity primary key,
  company_name text not null unique,
  industry text,
  contact_name text not null,
  contact_email text not null,
  account_tier text not null check (account_tier in ('starter','business','enterprise')),
  account_manager_id int references employees(id),
  annual_contract_value numeric(12,2),
  status text not null default 'active' check (status in ('active','at_risk','churned'))
);

create table projects (
  id int generated by default as identity primary key,
  name text not null unique,
  description text,
  status text not null check (status in ('planning','active','on_hold','completed','cancelled')),
  priority text not null default 'medium' check (priority in ('low','medium','high','critical')),
  start_date date,
  deadline date,
  budget numeric(12,2),
  spent numeric(12,2) not null default 0,
  owner_id int references employees(id),
  customer_id int references customers(id)
);

create table project_members (
  project_id int references projects(id) on delete cascade,
  employee_id int references employees(id),
  role_on_project text not null,
  allocation_percent int not null default 100 check (allocation_percent between 1 and 100),
  primary key (project_id, employee_id)
);

create table tasks (
  id int generated by default as identity primary key,
  project_id int not null references projects(id) on delete cascade,
  title text not null,
  description text,
  status text not null default 'todo' check (status in ('todo','in_progress','blocked','done')),
  priority text not null default 'medium' check (priority in ('low','medium','high','critical')),
  assignee_id int references employees(id),
  due_date date,
  estimated_hours numeric(6,1),
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  unique (project_id, title)
);

create table task_dependencies (
  task_id int references tasks(id) on delete cascade,
  depends_on_task_id int references tasks(id) on delete cascade,
  primary key (task_id, depends_on_task_id),
  check (task_id <> depends_on_task_id)
);

create table meetings (
  id int generated by default as identity primary key,
  title text not null,
  project_id int references projects(id),
  organizer_id int references employees(id),
  scheduled_at timestamptz not null,
  duration_minutes int not null default 30,
  notes text
);

create table meeting_attendees (
  meeting_id int references meetings(id) on delete cascade,
  employee_id int references employees(id),
  primary key (meeting_id, employee_id)
);

create table documents (
  id int generated by default as identity primary key,
  title text not null,
  doc_type text not null check (doc_type in ('policy','procedure','project_brief','meeting_notes','product_doc')),
  project_id int references projects(id),
  content text not null,
  created_at timestamptz not null default now()
);

-- Lock every table to the public, then allow n8n's private service_role
alter table departments enable row level security;
alter table employees enable row level security;
alter table customers enable row level security;
alter table projects enable row level security;
alter table project_members enable row level security;
alter table tasks enable row level security;
alter table task_dependencies enable row level security;
alter table meetings enable row level security;
alter table meeting_attendees enable row level security;
alter table documents enable row level security;

grant usage on schema public to service_role;
grant all on all tables in schema public to service_role;
grant all on all sequences in schema public to service_role;

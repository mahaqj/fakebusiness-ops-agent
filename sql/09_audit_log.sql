-- 09_audit_log.sql
-- Records every insert, update and delete on key tables, with the old and new row and the
-- database role that made the change (service_role = n8n, postgres = manual SQL editor).
-- Run last, so the seed data is not logged.

create table audit_log (
  id bigint generated by default as identity primary key,
  changed_at timestamptz not null default now(),
  table_name text not null,
  operation text not null check (operation in ('INSERT','UPDATE','DELETE')),
  row_id text,
  old_data jsonb,
  new_data jsonb,
  changed_by text default current_user
);

alter table audit_log enable row level security;
grant all on audit_log to service_role;
grant all on all sequences in schema public to service_role;

create function write_audit() returns trigger as $$
begin
  if tg_op = 'DELETE' then
    insert into audit_log (table_name, operation, row_id, old_data)
    values (tg_table_name, tg_op, old.id::text, to_jsonb(old));
    return old;
  elsif tg_op = 'UPDATE' then
    insert into audit_log (table_name, operation, row_id, old_data, new_data)
    values (tg_table_name, tg_op, new.id::text, to_jsonb(old), to_jsonb(new));
    return new;
  else
    insert into audit_log (table_name, operation, row_id, new_data)
    values (tg_table_name, tg_op, new.id::text, to_jsonb(new));
    return new;
  end if;
end;
$$ language plpgsql;

-- meeting_attendees has no single id column, so it gets its own function
create function write_audit_attendees() returns trigger as $$
begin
  if tg_op = 'DELETE' then
    insert into audit_log (table_name, operation, row_id, old_data)
    values (tg_table_name, tg_op, old.meeting_id || '-' || old.employee_id, to_jsonb(old));
    return old;
  else
    insert into audit_log (table_name, operation, row_id, new_data)
    values (tg_table_name, tg_op, new.meeting_id || '-' || new.employee_id, to_jsonb(new));
    return new;
  end if;
end;
$$ language plpgsql;

create trigger audit_tasks after insert or update or delete on tasks
for each row execute function write_audit();

create trigger audit_meetings after insert or update or delete on meetings
for each row execute function write_audit();

create trigger audit_agent_actions after insert or update or delete on agent_actions
for each row execute function write_audit();

create trigger audit_meeting_attendees after insert or delete on meeting_attendees
for each row execute function write_audit_attendees();
